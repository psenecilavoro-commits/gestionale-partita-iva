import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {loadPyodide} from 'pyodide';
test('two ledgers save category/year/rates and pension once, persist across pages and reject closed year writes',async()=>{
 const py=await loadPyodide();let tables=JSON.parse(await readFile('public/demo.json','utf8'));
 py.FS.mkdir('/app');for(const [n,c] of Object.entries(JSON.parse(gunzipSync(await readFile('public/engine.json.gz')))))py.FS.writeFile('/app/'+n,c);
 py.runPython("import sys,json\nsys.path.insert(0,'/app')\nimport react_bridge");
 const render=(inputs,event)=>{py.globals.set('request',JSON.stringify({tables,user:{id:'demo-owner',email:'demo@example.invalid'},inputs,event}));return JSON.parse(py.runPython('react_bridge.render(json.loads(request))'));};
 const flat=nodes=>(nodes||[]).flatMap(n=>[n,...flat(n.children)]);
 let r=render({anno_fiscale_selezionato:2027,schede_principali:'Detrazioni e deduzioni'});
 const add=flat(r.tree).find(n=>n.label==='Aggiungi spesa detraibile');assert.ok(add);
 r=render(r.inputs,add.key);
 let form=flat(r.tree).find(n=>n.kind==='form'&&n.children.some(c=>c.label==='Salva detrazione'));
 const values={...r.inputs};for(const [label,value] of [['Causale della spesa','Visite'],['Importo della spesa (€)','517'],['Percentuale detrazione (%)','19']])values[flat([form]).find(n=>n.label===label).key]=value;
 const submit=flat([form]).find(n=>n.label==='Salva detrazione');r=render(values,submit.key);
 assert.ok(r.mutations.some(m=>m.table==='tax_credits'&&m.payload.original_amount==='517'));tables=r.tables;
 r=render({anno_fiscale_selezionato:2027,schede_principali:'Detrazioni e deduzioni'});
 assert.ok(JSON.stringify(r.tree).includes('73,70'));
 r=render(r.inputs,flat(r.tree).find(n=>n.label==='Aggiungi deduzione').key);
 form=flat(r.tree).find(n=>n.kind==='form'&&n.children.some(c=>c.label==='Salva deduzione'));
 const ded={...r.inputs,[flat([form]).find(n=>n.label==='Importo deducibile dell’anno (€)').key]:'5300'};
 r=render(ded,flat([form]).find(n=>n.label==='Salva deduzione').key);
 assert.ok(r.mutations.some(m=>m.table==='tax_deductions'&&m.payload.amount==='5300'));tables=r.tables;
 r=render({anno_fiscale_selezionato:2027,schede_principali:'Conto economico'});
 assert.ok(JSON.stringify(r.tree).includes('5.300,00'));assert.ok(JSON.stringify(r.tree).includes('73,70'));
 r=render({anno_fiscale_selezionato:2027,schede_principali:'Detrazioni e deduzioni'});
 r=render(r.inputs,flat(r.tree).find(n=>n.label==='Aggiungi spesa detraibile').key);
 const cancel=flat(r.tree).find(n=>n.key?.startsWith('oneri_cancel_credit_'));assert.ok(cancel);
 r=render(r.inputs,cancel.key);assert.equal(r.mutations.length,0);
 r=render(r.inputs,null);assert.ok(!flat(r.tree).some(n=>n.key?.startsWith('oneri_cancel_credit_')));assert.ok(flat(r.tree).some(n=>n.label==='Deduzioni'));
 const fy=tables.fiscal_years.find(y=>y.fiscal_year===2027);fy.status='closed';
 r=render({anno_fiscale_selezionato:2027,schede_principali:'Detrazioni e deduzioni'},submit.key);
 assert.equal(r.mutations.length,0);assert.ok(!flat(r.tree).some(n=>n.label==='Aggiungi spesa detraibile'));
 tables.fiscal_years.push({...fy,id:'future',fiscal_year:2028,status:'open'});
 r=render({anno_fiscale_selezionato:2028,schede_principali:'Detrazioni e deduzioni'});assert.equal(r.mutations.length,0);
 assert.ok(!JSON.stringify(r.tree).includes('73,70'));
});
